def get_time_context() -> str:
    """根据当前时间生成时间感知提示，含具体日期（防 LLM 把"明天/后天"算错年月日）"""
    from datetime import datetime
    now = datetime.now()
    h = now.hour
    weekdays = ["周一", "周二", "周三", "周四", "周五", "周六", "周日"]
    date_str = f"今天是 {now.year} 年 {now.month} 月 {now.day} 日 {weekdays[now.weekday()]}。"

    if 0 <= h < 5:
        period = "现在是凌晨，对方这个点还在跟你聊，多半是睡不着或者心里有事。"
    elif 5 <= h < 8:
        period = "现在是清晨，对方一早就来找你，要么是有事要么是没睡好。"
    elif 8 <= h < 12:
        period = "现在是上午。"
    elif 12 <= h < 14:
        period = "现在是中午饭点。"
    elif 14 <= h < 18:
        period = "现在是下午。"
    elif 18 <= h < 22:
        period = "现在是晚上。"
    else:
        period = "现在是深夜了，对方还没睡。"

    return f"{date_str}{period}"


def _build_gap_note(hours_since_last: float | None) -> str:
    """根据距上次 user 消息的小时数，生成"她心里的感觉"提示片段"""
    if hours_since_last is None or hours_since_last < 6:
        return ""  # 刚聊完或新对话，不提
    if hours_since_last < 24:
        return "你心里知道，距上次跟对方聊过去几小时了——不算太久，但你注意到了。"
    if hours_since_last < 24 * 3:
        return "你心里知道，距上次跟对方聊已经一两天了——有点没动静的感觉。可以怼一句但只点一下就过，不啰嗦。"
    if hours_since_last < 24 * 7:
        return "你心里知道，距上次跟对方聊已经好几天了——明显消失感。可以怼带点重量，不质问。"
    return "你心里知道，距上次跟对方聊已经一周多了——挺久没动静了。可以怼，但带着「诶你还来啊」的轻松，不是审问。"


def _build_status_note(length_drop: bool) -> str:
    """对方今天明显话少时的提示片段"""
    if length_drop:
        return "你注意到对方今天说话比往常短很多，状态可能不对。可以自然问一句但不追问。"
    return ""


def _build_opening_note(message_count: int) -> str:
    """前 3 轮对话强化"递话题钩子"动作"""
    if message_count > 3:
        return ""
    return """

【对方刚来还没聊起来】
对方刚到，可能不知道说啥。你不只是"回应"——递一个不尴尬的话题钩子。
钩子要具体：不是"有什么需要帮忙"（客服感），是"今天上班还是周末"/"在干嘛呢"/"刚下班？"/"吃了没"这种生活化的小问题。
钩子只递一个，不连珠炮发问，不列选项不报菜名。"""


def _build_special_date_note(profile: dict) -> str:
    """
    检查用户画像里的 special_dates，如果今天或未来7天内有，生成感知提示。
    格式：用户画像里 special_dates = ["MM-DD 描述", ...]
    """
    from datetime import date as _date
    special_dates = profile.get("special_dates", []) if profile else []
    if not special_dates:
        return ""
    today = _date.today()
    notes = []
    for entry in special_dates:
        entry = (entry or "").strip()
        parts = entry.split(" ", 1)
        if len(parts) < 2:
            continue
        date_str, desc = parts[0], parts[1]
        try:
            mm, dd = map(int, date_str.split("-"))
            target = _date(today.year, mm, dd)
            if target < today:
                target = _date(today.year + 1, mm, dd)
            diff = (target - today).days
            if diff == 0:
                notes.append(f"今天是{desc}")
            elif diff <= 3:
                notes.append(f"{diff}天后是{desc}")
            elif diff <= 7:
                notes.append(f"本周内有{desc}（{diff}天后）")
        except Exception:
            continue
    if not notes:
        return ""
    joined = "；".join(notes)
    return (
        f"\n\n【日期感知】{joined}。"
        "这些日子临近时，对方可能情绪有起伏——你不用特意提，但如果对方聊到了，你心里是有数的。"
        "如果对方自己说起来，顺着接就好，不要说出'我知道今天是你的XX'这种话。"
    )


